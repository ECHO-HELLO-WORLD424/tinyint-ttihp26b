def run_git(*args):
    return subprocess.run(["git"] + list(args), capture_output=True,
                          text=True, cwd=C.REPO, check=True).stdout.strip()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def utc_now_iso():
    return (datetime.datetime.now(datetime.timezone.utc)
            .replace(microsecond=0).isoformat().replace("+00:00", "Z"))


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def git_identity():
    dirty = run_git("status", "--porcelain") != ""
    return {
        "git_commit": run_git("rev-parse", "HEAD"),
        "branch": run_git("rev-parse", "--abbrev-ref", "HEAD"),
        "git_dirty": dirty,
    }


def ci_identity():
    """CI identity from the staged artifacts + pinned provenance."""
    commit_id = load_json(os.path.join(RUN_DIR, "commit_id.json"))
    resolved = load_json(os.path.join(RUN_DIR, "resolved.json"))
    meta = resolved.get("meta") or {}
    # PDK revision from the resolved PDK_ROOT path (CI ciel store layout).
    m = re.search(r"/versions/([0-9a-f]{40})", resolved.get("PDK_ROOT", ""))
    pdk_rev_ci = m.group(1) if m else None
    assert pdk_rev_ci is None or pdk_rev_ci == C.CIEL_PDK_REV, \
        "staged PDK revision differs from pinned tools/common.py value"
    return {
        "run_id": RUN_ID,
        "run_url": RUN_URL,
        "workflow": WORKFLOW,
        "ci_runner": CI_RUNNER,
        "commit_id_json": {
            "app": commit_id.get("app"),
            "repo": commit_id.get("repo"),
            "commit": commit_id.get("commit"),
            "workflow_url": commit_id.get("workflow_url"),
        },
        "tool_image": C.LL_IMAGE,
        "librelane_version": (meta or {}).get("librelane_version"),
        "sta_step": "54-openroad-stapostpnr",
        "sta_step_runtime": read_sta_runtime(),
        "pdk": resolved.get("PDK"),
        "pdk_ciel_rev": C.CIEL_PDK_REV,
        "pdk_ciel_rev_source": "resolved.json PDK_ROOT (== tools/common.py)",
    }


def read_sta_runtime():
    with open(os.path.join(STA_DIR, "runtime.txt"), encoding="utf-8") as f:
        return f.read().strip()


def hash_all_files():
    """Hash every file under RUN_DIR (excluding this script's outputs)."""
    files = {}
    for root, _dirs, names in os.walk(RUN_DIR):
        for name in sorted(names):
            if name in GENERATED:
                continue
            path = os.path.join(root, name)
            rel = os.path.relpath(path, RUN_DIR)
            files[rel] = {
                "size": os.path.getsize(path),
                "sha256": sha256_file(path),
            }
    return dict(sorted(files.items()))


def parse_summary_rpt():
    """Per-corner setup/hold worst slacks from sta summary.rpt.

    Columns (bar-separated): [0]=corner, [1]=hold worst slack, [2]=reg-to-reg
    hold, [3]=hold TNS, [4]=hold violation count, [6]=setup worst slack,
    [7]=reg-to-reg setup, [8]=setup TNS, [9]=setup violation count.
    """
    out = {}
    with open(os.path.join(STA_DIR, "summary.rpt"), encoding="utf-8") as f:
        for line in f:
            if "│" not in line:
                continue
            cols = [c.strip() for c in line.split("│")]
            if len(cols) < 10:
                continue
            corner = cols[0]
            if corner in ("", "Overall") or not corner.startswith("nom_"):
                continue
            out[corner] = {
                "hold_worst_slack_ns": float(cols[1]),
                "setup_worst_slack_ns": float(cols[6]),
                "hold_violations": int(cols[4]),
                "setup_violations": int(cols[9]),
            }
    return out


def extract_signoff():
    """Signoff numbers from metrics.json, cross-checked against summary.rpt."""
    metrics = load_json(os.path.join(RUN_DIR, "metrics.json"))
    corners = {}
    for corner in C.CORNER_NAMES:
        p = "__corner:" + corner
        corners[corner] = {
            "setup_worst_slack_ns": metrics["timing__setup__ws" + p],
            "setup_worst_slack_r2r_ns": metrics["timing__setup_r2r__ws" + p],
            "setup_tns_ns": metrics["timing__setup__tns" + p],
            "setup_violations": metrics["timing__setup_vio__count" + p],
            "hold_worst_slack_ns": metrics["timing__hold__ws" + p],
            "hold_worst_slack_r2r_ns": metrics["timing__hold_r2r__ws" + p],
            "hold_tns_ns": metrics["timing__hold__tns" + p],
            "hold_violations": metrics["timing__hold_vio__count" + p],
            "max_slew_violations": metrics[
                "design__max_slew_violation__count" + p],
            "max_fanout_violations": metrics[
                "design__max_fanout_violation__count" + p],
            "max_cap_violations": metrics[
                "design__max_cap_violation__count" + p],
        }
    # summary.rpt must agree with the metrics (report rounds to 4 decimals).
    for corner, vals in parse_summary_rpt().items():
        m = corners[corner]
        for key in ("setup_worst_slack_ns", "hold_worst_slack_ns"):
            assert abs(round(m[key], 4) - vals[key]) < 1e-9, \
                "summary.rpt vs metrics.json mismatch: %s %s" % (corner, key)
        assert m["setup_violations"] == vals["setup_violations"]
        assert m["hold_violations"] == vals["hold_violations"]

    def m(key):
        return metrics[key]

    drc_lvs = {
        "magic_drc_errors": m("magic__drc_error__count"),
        "magic_illegal_overlaps": m("magic__illegal_overlap__count"),
        "route_drc_errors": m("route__drc_errors"),
        "lvs_errors": m("design__lvs_error__count"),
        "lvs_device_differences": m("design__lvs_device_difference__count"),
        "lvs_net_differences": m("design__lvs_net_difference__count"),
        "lvs_property_fails": m("design__lvs_property_fail__count"),
        "antenna_violating_nets": m("antenna__violating__nets"),
        "antenna_violating_pins": m("antenna__violating__pins"),
        "route_antenna_violations": m("route__antenna_violation__count"),
        "power_grid_violations": m("design__power_grid_violation__count"),
    }
    if all(v == 0 for v in drc_lvs.values()):
        drc_lvs["note"] = ("all checks clean per staged metrics.json; the "
                           "DRC/LVS/antenna report files themselves are "
                           "recorded-in-CI-only at " + RUN_URL)
    else:
        drc_lvs["note"] = ("nonzero result(s) recorded in staged metrics.json;"
                           " see checker reports in the full CI artifact at "
                           + RUN_URL)
    drc_lvs["source"] = "artifacts/run-%s/metrics.json (staged subset)" % RUN_ID

    return {
        "corners": corners,
        "instances": {
            "total": m("design__instance__count"),
            "stdcell": m("design__instance__count__stdcell"),
            "fill": m("design__instance__count__class:fill_cell"),
            "total_area_um2": m("design__instance__area"),
            "stdcell_area_um2": m("design__instance__area__stdcell"),
        },
        "utilization": {
            "design": m("design__instance__utilization"),
            "stdcell": m("design__instance__utilization__stdcell"),
        },
        "drc_lvs_antenna": drc_lvs,
        "lint": {
            "errors": m("design__lint_error__count"),
            "warnings": m("design__lint_warning__count"),
            "inferred_latches": m("design__inferred_latch__count"),
        },
        "power_total_w": m("power__total"),
    }


