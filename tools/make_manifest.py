        "SYNTH_STRATEGY", "SYNTH_HIERARCHY_MODE", "SYNTH_ADDER_TYPE",
        "SYNTH_SIZING", "SYNTH_DRIVING_CELL", "SYNTH_TIE_UNDEFINED",
        "SYNTH_PARAMETERS", "USE_SLANG",
        "RT_MIN_LAYER", "RT_MAX_LAYER",
        "MAX_FANOUT_CONSTRAINT", "MAX_TRANSITION_CONSTRAINT",
        "MAX_CAPACITANCE_CONSTRAINT", "CLOCK_UNCERTAINTY_CONSTRAINT",
        "CLOCK_TRANSITION_CONSTRAINT", "TIME_DERATING_CONSTRAINT",
        "IO_DELAY_CONSTRAINT",
