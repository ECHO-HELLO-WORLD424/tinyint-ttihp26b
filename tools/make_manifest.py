def write_markdown(man, path):
    f = man["files"]
    gds = "gds/tt_um_echoworld424_tpv.gds"
    nl = "nl/tt_um_echoworld424_tpv.nl.v"
    spef = "spef/nom/tt_um_echoworld424_tpv.nom.spef"

    def h(rel):
        return "`%s`" % f[rel]["sha256"] if rel in f else "MISSING"

    lines = [
        "# Final submission build manifest (run %s)" % RUN_ID,
        "",
        "Generated by `tools/make_manifest.py`; machine-readable copy in",
        "`manifest.json` next to this file. Git-dirty flag at generation:",
        "**%s** (this manifest hashes the staged run artifacts, not the"
        " working tree)." % ("yes" if man["git"]["git_dirty"] else "no"),
        "",
        "| Item | Value |",
        "| --- | --- |",
        "| Commit | `%s` |" % man["git"]["staged_run_commit"],
        "| Branch | `%s` |" % man["git"]["branch"],
        "| CI run | [gds.yaml run %s](%s) (all green: gds + precheck + gl_test + viewer) |" % (RUN_ID, RUN_URL),
        "| Tool image | `%s` |" % man["ci"]["tool_image"],
        "| LibreLane | %s (resolved.json meta) |" % man["ci"]["librelane_version"],
        "| PDK | %s @ ciel `%s` |" % (man["ci"]["pdk"], man["ci"]["pdk_ciel_rev"]),
        "| STA step | %s (runtime %s) |" % (man["ci"]["sta_step"], man["ci"]["sta_step_runtime"]),
        "",
        "## Signoff summary",
        "",
        "| Corner | Setup worst slack (ns) | Hold worst slack (ns) | Setup TNS (ns) | Setup vio | Hold vio |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for corner, c in man["signoff"]["corners"].items():
        lines.append(
            "| %s | %+.4f | %+.4f | %+.4f | %d | %d |" % (
                corner, c["setup_worst_slack_ns"], c["hold_worst_slack_ns"],
                c["setup_tns_ns"], c["setup_violations"],
                c["hold_violations"]))
    inst = man["signoff"]["instances"]
    util = man["signoff"]["utilization"]
    d = man["signoff"]["drc_lvs_antenna"]
    lines += [
        "",
        "| Instances | Utilization | Magic DRC | Route DRC | LVS | Antenna | Power grid |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        "| %d total (%d stdcell + %d fill) | %.2f%% design / %.2f%% stdcell | %d | %d | %d | %d | %d |" % (
            inst["total"], inst["stdcell"], inst["fill"],
            100 * util["design"], 100 * util["stdcell"],
            d["magic_drc_errors"], d["route_drc_errors"], d["lvs_errors"],
            d["route_antenna_violations"], d["power_grid_violations"]),
        "",
        "DRC/LVS/antenna values are recorded in the staged `metrics.json`;"
        " the checker report files themselves are recorded-in-CI-only"
        " ([run %s](%s))." % (RUN_ID, RUN_URL),
        "",
        "## Headline artifact hashes (SHA-256)",
        "",
        "| Artifact | Path | SHA-256 |",
        "| --- | --- | --- |",
        "| Final GDS | `%s` | %s |" % (gds, h(gds)),
        "| Final netlist | `%s` | %s |" % (nl, h(nl)),
        "| Nominal SPEF | `%s` | %s |" % (spef, h(spef)),
        "",
        "## Reproduce",
        "",
        "```sh",
    ] + man["reproduce"] + ["```"]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    man = {
        "schema": {
            "name": "tpv-final-build-manifest",
            "version": 1,
            "generated_at": utc_now_iso(),
            "notes": ("Final submission build identity for "
                      "PRE_SILICON_ACTION_PLAN item P2.2; hashes cover the "
                      "staged run-33839023290 artifacts only."),
        },
        "git": dict(git_identity(), staged_run_commit=C.GIT_COMMIT),
        "ci": ci_identity(),
        "config": extract_config(),
        "signoff": extract_signoff(),
        "files": hash_all_files(),
        "reproduce": REPRODUCE,
    }
    man_path = os.path.join(RUN_DIR, "manifest.json")
    with open(man_path, "w", encoding="utf-8") as fh:
        json.dump(man, fh, indent=2)
        fh.write("\n")
    write_markdown(man, os.path.join(RUN_DIR, "MANIFEST.md"))
    print("wrote", man_path)
    print("wrote", os.path.join(RUN_DIR, "MANIFEST.md"))
    print("hashed", len(man["files"]), "files")


if __name__ == "__main__":
    main()
